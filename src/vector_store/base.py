# src/vector_store/base.py
"""Протокол векторного хранилища.

Любой бэкенд (FAISS, Qdrant, Weaviate, ...) реализует этот интерфейс.
Весь остальной код (KnowledgeBaseIndexer, BaseRetriever, RetrievalEvaluationCallback)
принимает ``BaseVectorStore`` — смена бэкенда требует только изменения конфига.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class BaseVectorStore(Protocol):
    """Протокол для векторного хранилища.

    ``@runtime_checkable`` позволяет использовать ``isinstance(obj, BaseVectorStore)``
    для проверки совместимости без наследования.

    Реализующий класс обязан предоставить все перечисленные методы и свойства.
    Типы аргументов намеренно широкие (``np.ndarray``) — бэкенд сам решает
    как конвертировать в нужный формат.
    """

    # ------------------------------------------------------------------
    # Свойства состояния
    # ------------------------------------------------------------------

    @property
    def embedding_dim(self) -> int:
        """Размерность векторов с которой инициализировано хранилище."""
        ...

    @property
    def ntotal(self) -> int:
        """Общее число векторов в индексе."""
        ...

    @property
    def existing_doc_ids(self) -> set[str]:
        """Множество всех ``doc_id`` уже присутствующих в хранилище.

        Используется ``KnowledgeBaseIndexer`` для точной дедупликации.
        Реализация может кэшировать результат и инвалидировать при insert/reset.
        """
        ...

    # ------------------------------------------------------------------
    # Запись
    # ------------------------------------------------------------------

    def insert(self, embeddings: Any, metadata: list[dict[str, Any]]) -> None:
        """Добавляет векторы и метаданные в хранилище.

        Args:
            embeddings: Матрица векторов формы ``(N, embedding_dim)``.
            metadata: Список словарей длиной N. Каждый словарь должен содержать
                ключ ``'doc_id'`` для поддержки дедупликации.

        Raises:
            ValueError: При несоответствии размерностей или длин.
        """
        ...

    # ------------------------------------------------------------------
    # Поиск
    # ------------------------------------------------------------------

    def search(
        self,
        query_embeddings: Any,
        top_k: int = 5,
        filter_metadata: dict[str, Any] | None = None,
    ) -> list[list[dict[str, Any]]]:
        """Возвращает top_k ближайших документов для каждого запроса.

        Args:
            query_embeddings: Матрица запросов формы ``(N, embedding_dim)``.
            top_k: Максимальное число результатов на запрос.
            filter_metadata: Точная фильтрация по полям метаданных (AND-семантика).
                ``None`` — без фильтрации.

        Returns:
            Список длиной N. Каждый элемент — список dict
            ``{'score': float, 'metadata': dict}``, отсортированный по убыванию score.
        """
        ...

    # ------------------------------------------------------------------
    # Персистентность
    # ------------------------------------------------------------------

    def save(self, directory: str | Path) -> None:
        """Сохраняет состояние хранилища на диск.

        Args:
            directory: Путь к директории. Создаётся если не существует.
        """
        ...

    def reset(self) -> None:
        """Полностью очищает хранилище (индекс + метаданные)."""
        ...
